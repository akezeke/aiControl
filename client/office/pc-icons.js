// Draws the icon at (x, y), each pixel `scale` squares; a run of one colour along a row is a single fillRect.
export function paint(g, icon, x, y, scale = 1) {
  icon.rows.forEach((row, j) => {
    for (let i = 0; i < row.length;) {
      const ch = row[i];
      if (ch === '.') { i++; continue; }
      let end = i + 1; while (end < row.length && row[end] === ch) end++;
      g.fillStyle = PICO_PALETTE[parseInt(ch, 16)]; g.fillRect(x + i * scale, y + j * scale, (end - i) * scale, scale); i = end;
    }
  });
}
export function iconCanvas(icon, scale, doc = document) {
  const canvas = doc.createElement('canvas'); canvas.width = icon.w * scale; canvas.height = icon.h * scale;
  paint(canvas.getContext('2d'), icon, 0, 0, scale);
  return canvas;
}
// The frames side by side in one image, for a CSS background stepped with steps(frames.length).
export function stripUrl(frames, scale, doc = document) {
  const canvas = doc.createElement('canvas'); canvas.width = frames[0].w * scale * frames.length; canvas.height = frames[0].h * scale;
  const g = canvas.getContext('2d');
  frames.forEach((frame, i) => paint(g, frame, i * frame.w * scale, 0, scale));
  return canvas.toDataURL();
}
export const cursorUrl = (icon, scale, doc = document) => iconCanvas(icon, scale, doc).toDataURL();
